def insert_after(paragraph, new_paragraph):
    paragraph._p.addnext(new_paragraph._p)


def add_para_after(anchor, text, style):
    p = anchor._parent.add_paragraph(text, style=style)
    insert_after(anchor, p)
    return p


def add_bullet(anchor, text):
    return add_para_after(anchor, text, "List Bullet")


def add_number(anchor, text):
    return add_para_after(anchor, text, "List Number")


def remove_paragraph(paragraph):
    paragraph._element.getparent().remove(paragraph._element)


